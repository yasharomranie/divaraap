import json
import subprocess
from pathlib import Path
from playwright.sync_api import sync_playwright
root = Path(__file__).resolve().parents[2]
state = json.loads((root/'storage/framework/order-review.json').read_text())
base = 'http://localhost:8000'
with sync_playwright() as p:
    browser = p.chromium.launch(executable_path='/usr/bin/chromium',args=['--no-sandbox','--disable-dev-shm-usage'])
    customer = browser.new_context(viewport={'width':390,'height':844})
    page = customer.new_page()
    errors=[]
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.goto(base+'/login',wait_until='networkidle')
    page.locator('#email').fill(state['email'])
    page.locator('#password').fill('Browser-test-123!')
    page.locator('button[type="submit"]').click()
    page.wait_for_url(lambda u:'/login' not in u)
    page.goto(base+'/lang/fa',wait_until='networkidle')
    page.goto(base+'/panel/advertising-orders/create',wait_until='networkidle')
    for width in [360,390,768,1440]:
        page.set_viewport_size({'width':width,'height':900})
        assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
    page.set_viewport_size({'width':390,'height':844})
    page.get_by_label('عنوان درخواست',exact=True).fill('درخواست آزمایش مرورگر')
    page.get_by_label('توضیح درخواست',exact=True).fill('معرفی فروشگاه و محصولات با شرایط مشخص')
    page.locator('#order-placement').select_option('home-top')
    page.locator('#order-days').fill('7')
    page.locator('#order-budget').fill('1000000')
    page.locator('#order-title').focus()
    assert page.locator('#order-title').evaluate('(e)=>getComputedStyle(e).outlineStyle != "none" || getComputedStyle(e).boxShadow != "none"')
    assert page.locator('.advertising-orders').evaluate('(e)=>getComputedStyle(e).fontFamily.includes("Vazirmatn")')
    page.screenshot(path='/tmp/advertising-order-form-mobile.png',full_page=True)
    page.get_by_role('button',name='ارسال درخواست',exact=True).click()
    page.wait_for_url(lambda u:'/advertising-orders/' in u and '/create' not in u)
    order_id=int(page.url.rstrip('/').split('/')[-1])
    assert 'در انتظار بررسی' in page.locator('.advertising-orders').inner_text()
    admin=browser.new_context(viewport={'width':1440,'height':1000})
    ap=admin.new_page()
    ap.on('pageerror',lambda e:errors.append(str(e)))
    ap.goto(base+'/admin/login',wait_until='networkidle')
    ap.get_by_role('button',name='Admin (a@a.com)',exact=True).click()
    ap.wait_for_url(base+'/admin')
    ap.goto(base+'/lang/fa',wait_until='networkidle')
    ap.goto(base+'/admin/advertising-orders',wait_until='networkidle')
    row=ap.locator('tr').filter(has=ap.locator(f'a[href="{base}/panel/advertising-orders/{order_id}"]'))
    row.get_by_role('button',name='اعلام مبلغ و صدور صورتحساب',exact=True).click()
    ap.get_by_label('مبلغ (ریال)',exact=False).fill('1000000')
    ap.get_by_label('پاسخ و شرایط اعلام‌شده مدیر',exact=False).fill('هفت روز نمایش پس از آماده‌سازی و هماهنگی؛ مبلغ یک میلیون ریال')
    ap.get_by_role('button',name='تایید',exact=True).click()
    ap.get_by_label('مبلغ (ریال)',exact=False).wait_for(state='hidden')
    page.reload(wait_until='networkidle')
    assert 'پیشنهاد آماده است' in page.locator('.advertising-orders').inner_text()
    assert '1,000,000' in page.locator('.advertising-orders').inner_text()
    page.get_by_role('button',name='پذیرش شرایط و مبلغ پیشنهاد',exact=True).click()
    page.wait_for_load_state('networkidle')
    assert 'پذیرفته‌شده' in page.locator('.advertising-orders').inner_text()
    out=subprocess.check_output(['docker','exec','-w','/app','divaraap-php','php','tests/Browser/order-fixtures.php','settle'],text=True)
    assert 'Settled.' in out,out
    page.reload(wait_until='networkidle')
    assert 'تسویه‌شده' in page.locator('.advertising-orders').inner_text()
    page.get_by_role('link',name='مشاهده رسید',exact=True).click()
    page.wait_for_url(lambda u:'/advertising-invoices/' in u)
    assert '1,000,000' in page.locator('.advertising-invoice').inner_text()
    ap.reload(wait_until='networkidle')
    row=ap.locator('tr').filter(has=ap.locator(f'a[href="{base}/panel/advertising-orders/{order_id}"]'))
    row.get_by_role('button',name='تأیید انجام سفارش',exact=True).click()
    ap.get_by_text('فقط پس از انجام خدمات توافق‌شده تأیید کنید.',exact=False).wait_for()
    ap.get_by_role('button',name='کمپین*',exact=True).click()
    ap.locator('input[role="combobox"]').fill('Order browser campaign')
    ap.get_by_role('option',name='Order browser campaign',exact=True).click()
    ap.get_by_role('button',name='تایید',exact=True).click()
    row.get_by_text('انجام سفارش تأیید شد',exact=True).wait_for()
    page.goto(base+'/lang/en',wait_until='networkidle')
    page.goto(base+'/panel/advertising-orders/'+str(order_id),wait_until='networkidle')
    assert page.locator('html').get_attribute('dir')=='ltr'
    assert 'Fulfillment confirmed' in page.locator('.advertising-orders').inner_text()
    assert not errors,errors
    browser.close()
print('PASS: customer request form, admin quote, owner acceptance, linked settlement/receipt and admin completion, four widths, RTL/LTR, font and keyboard focus')
